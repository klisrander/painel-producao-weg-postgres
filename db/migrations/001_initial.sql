CREATE TABLE users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text NOT NULL UNIQUE CHECK (length(username) BETWEEN 1 AND 60),
 oidc_issuer text NOT NULL, oidc_subject text NOT NULL,
 name text NOT NULL DEFAULT '', job text NOT NULL DEFAULT '',
 role text NOT NULL CHECK (role IN ('admin','operador')),
 start text NOT NULL, "end" text NOT NULL,
 active integer NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
 turno text, section text NOT NULL CHECK (section IN ('bobinagem','montagem','montagem-ib')),
 general_admin integer NOT NULL DEFAULT 0 CHECK (general_admin IN (0,1)),
 permissions text CHECK (permissions IS NULL OR jsonb_typeof(permissions::jsonb)='array'),
 UNIQUE(oidc_issuer,oidc_subject), CHECK (general_admin=0 OR role='admin')
);
CREATE TABLE records (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 section text NOT NULL,
 kind text NOT NULL CHECK(kind IN ('producao','perturbacao')),
 owner integer NOT NULL REFERENCES users(id), created text NOT NULL, updated text NOT NULL,
 data text NOT NULL CHECK(jsonb_typeof(data::jsonb)='object')
);
CREATE INDEX records_section_date ON records(section, ((data::jsonb)->>'data'));
CREATE TABLE audit (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 section text NOT NULL, at text NOT NULL, actor text NOT NULL, action text NOT NULL,
 record_id integer, before_data text, after_data text
);
CREATE INDEX audit_section_id ON audit(section,id DESC);
CREATE TABLE sessions (
 token text PRIMARY KEY, user_id integer NOT NULL REFERENCES users(id),
 expires bigint NOT NULL, absolute_expires bigint NOT NULL
);
CREATE INDEX session_expiry ON sessions(expires);
CREATE TABLE oidc_requests (
 state_hash text PRIMARY KEY, binding_hash text NOT NULL,
 verifier text NOT NULL, nonce text NOT NULL, return_to text NOT NULL,
 expires bigint NOT NULL
);
CREATE TABLE settings (key text PRIMARY KEY, value text NOT NULL);
CREATE TABLE goal_changes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 section text NOT NULL, effective_date text NOT NULL, line text NOT NULL, stage text NOT NULL,
 meta1 integer CHECK(meta1>=0), meta2 integer CHECK(meta2>=0), meta3 integer CHECK(meta3>=0),
 third_enabled integer NOT NULL CHECK(third_enabled IN(0,1)), at text NOT NULL, actor text NOT NULL
);
CREATE INDEX goal_section_date ON goal_changes(section,effective_date,id);
CREATE TABLE performance_changes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 section text NOT NULL, effective_date text NOT NULL, line text NOT NULL, stage text NOT NULL,
 turno text NOT NULL CHECK(turno IN('1','2','3')),
 capacity integer CHECK(capacity>=0), efficiency_target numeric(5,2) CHECK(efficiency_target BETWEEN 0 AND 100),
 at text NOT NULL, actor text NOT NULL,
 CHECK ((capacity IS NULL)=(efficiency_target IS NULL))
);
CREATE INDEX performance_section_date ON performance_changes(section,effective_date,id);
CREATE TABLE projection_plans (
 id text PRIMARY KEY, section text NOT NULL, name text NOT NULL, stage text NOT NULL,
 start_date text NOT NULL, initial_backlog integer NOT NULL,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 data text NOT NULL CHECK(jsonb_typeof(data::jsonb)='object'),
 created text NOT NULL, updated text NOT NULL, actor text NOT NULL
);
CREATE INDEX projection_section_updated ON projection_plans(section,updated);
CREATE TABLE projection_revisions (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plan_id text NOT NULL REFERENCES projection_plans(id), section text NOT NULL,
 revision integer NOT NULL CHECK(revision>0), at text NOT NULL, actor text NOT NULL,
 snapshot text NOT NULL CHECK(jsonb_typeof(snapshot::jsonb)='object'),
 UNIQUE(plan_id,revision)
);
CREATE INDEX projection_revision_section ON projection_revisions(section,plan_id);
